import { _electron as electron } from 'playwright';
import {waitForShell} from './electron-shell.mjs';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const localDate = new Intl.DateTimeFormat('en-CA', { timeZone: 'Australia/Sydney', year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date());
const evidenceDir = resolve(`evidence/${localDate}/M0-04/${new Date().toISOString().replace(/[.:]/g, '-')}`);
await mkdir(evidenceDir, { recursive: true });
const env = { ...process.env, W2P_SMOKE: '1', W2P_DATA_DIR: resolve('.runtime/smoke') };
delete env.ELECTRON_RUN_AS_NODE;
const application = await electron.launch({ args: [resolve('apps/desktop')], env, timeout: 30000 });
const checks = [];
try {
  const shell = await waitForShell(application);
  await shell.waitForFunction(() => !!window.w2p);
  const target = await application.waitForEvent('window', { predicate: page => page.url().includes('/fixture'), timeout: 15000 }).catch(async () => application.windows().find(page => page.url().includes('/fixture')));
  if (!target) throw new Error('Target WebContentsView did not load');
  await target.waitForSelector('#orders');
  checks.push({ check: 'fixture-loaded', ok: await target.title() === 'WebToPrototype 本地采集验证' });
  checks.push({ check: 'target-has-no-node-or-app-bridge', ok: await target.evaluate(() => typeof window.require === 'undefined' && typeof window.w2p === 'undefined') });
  await shell.getByRole('button', { name: '点选页面元素' }).click();
  await target.locator('#details').hover();
  await target.locator('#details').click();
  await shell.waitForFunction(() => document.querySelector('#output')?.textContent?.includes('details'));
  checks.push({ check: 'selection-does-not-open-dialog', ok: await target.locator('#detail-dialog').evaluate(node => !node.open) });
  await shell.getByText('诊断与文件工具', { exact: true }).click();
  await shell.getByRole('button', { name: '读取选中布局' }).click();
  await shell.waitForFunction(() => document.querySelector('#output')?.textContent?.includes('actual_dom_probe'));
  const text = await shell.locator('#output').textContent();
  const record = JSON.parse(text);
  checks.push({ check: 'isolated-world-layout-read', ok: record.snapshot.selection.id === 'details' && record.snapshot.selection.rect.width > 0 });
  await target.locator('#details').click();
  checks.push({ check: 'normal-click-restored', ok: await target.locator('#detail-dialog').evaluate(node => node.open) });
  await target.locator('#close-dialog').click();
  await target.screenshot({ path: resolve(evidenceDir, 'fixture.png') });
  await shell.screenshot({ path: resolve(evidenceDir, 'desktop.png') });
  await writeFile(resolve(evidenceDir, 'dom-probe.json'), JSON.stringify(record,null,2));
  const runtime = await application.evaluate(() => ({ electron: process.versions.electron, chrome: process.versions.chrome, node: process.versions.node }));
  await writeFile(resolve(evidenceDir, 'smoke-report.json'), JSON.stringify({ evidenceKind: 'actual_electron_smoke', at: new Date().toISOString(), runtime, checks, figmaTested: false },null,2));
  console.log(JSON.stringify({ runtime, checks },null,2));
  if (checks.some(check => !check.ok)) throw new Error('Desktop smoke checks failed');
} finally { await application.close(); }
